# Taking numbers as input
a = int(input ("Enter a number: "))
b = int(input ("Enter another number: "))

# Comparing numbers
print(f"Is {a} equal to {b}? => {a == b}")                     # numbers are equal
print(f"Is {a} not equal to {b}? => {a != b}")                 # numbers are not equal
print(f"Is {a} greater than {b}? => {a > b}")                  # numbers are greater than
print(f"Is {a} less than {b}? => {a < b}")                     # numbers are less than
print(f"Is {a} greater than or equal to {b}? => {a >= b}")     # numbers are greater than or equal to
print(f"Is {a} less than or equal to {b}? => {a <= b}")        # numbers are less than or equal to