a = 302
b = 14
print("Value of a is:", a)
print("Value of b is:", b)
print("Addition of a and b is:", a + b)
print("Subtraction of a and b is:", a - b)
print("Multiplication of a and b is:", a * b)
print("Division of a and b is:", a / b)
print("Floor Division of a and b is:", a // b)  # Floor division returns the largest integer less than or equal to the division result
print("Modulus of a and b is:", a % b)          # Modulus returns the remainder of the division
print("Exponentiation of a and b is:", a ** b)  # Exponentiation returns the result of raising a to the power of b